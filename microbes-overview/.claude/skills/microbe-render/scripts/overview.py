#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = []
# ///
"""Build per-set OVERVIEW.md galleries (final/last image per microbe × style +
the set's status), gather the finals into each set folder, and a top-level
renders/OVERVIEW.md index.

"Final/last" image per (microbe, theme) = the highest-numbered attempt's AVIF.
These are copied to <SET>/finals/<microbe>__<theme>.avif so the set folder holds
a flat gallery of finals (plus each microbe's reference micrograph and labelled SVG).

Reads the per-microbe metadata (<microbe>.render.meta.json). Run after status.py.
Usage: overview.py [--renders-root renders]
"""
from __future__ import annotations
import argparse, json, glob, re, shutil, time
from pathlib import Path

THEME_ORDER = ["textbook", "sem", "3d", "watercolor"]
THEME_LABEL = {"textbook": "Textbook", "sem": "SEM", "3d": "3D", "watercolor": "Watercolor"}
# Styles that carry a labelled SVG (sem + reference are shown unlabelled).
LABELLED_THEMES = ["textbook", "3d", "watercolor"]

# German umlaut fixes for descriptions stored with ae/oe/ue (mirror assemble_md.py).
UML = {"Staebchen": "Stäbchen", "staebchen": "stäbchen", "stabfoermige": "stabförmige",
       "stabfoermigen": "stabförmigen", "Gummibaerchen": "Gummibärchen", "koennen": "können",
       "boese": "böse", "boesen": "bösen", "Naehrstoffe": "Nährstoffe", "Naehrstoffen": "Nährstoffen",
       "gefaehrlich": "gefährlich", "uebermaessiger": "übermäßiger", "foerdert": "fördert",
       "Staemme": "Stämme", "aeussere": "äußere", "aeusseren": "äußeren", "duenne": "dünne",
       "Laenge": "Länge", "laengliche": "längliche", "Oberflaeche": "Oberfläche",
       "oekologisch": "ökologisch", "zaehlt": "zählt", "Antikoerper": "Antikörper",
       "Huellstrukturen": "Hüllstrukturen", "verdraengen": "verdrängen", "ergaenzt": "ergänzt",
       "Ernaehrung": "Ernährung", "fuer": "für"}


def fix_de(s: str) -> str:
    for a, b in UML.items():
        s = s.replace(a, b)
    return s


def load_desc(set_dir, microbe):
    p = set_dir / f"{microbe}.descriptions.json"
    if not p.exists():
        return None
    d = json.loads(p.read_text())
    return {k: (fix_de(v) if k.endswith("_de") else v) for k, v in d.items()}


def cell(md_caption, img_md):
    return f"{md_caption}<br>{img_md}" if img_md else "—"


def build_root_index(by_set, root):
    """Rich renders/OVERVIEW.md: sets as sections, microbes alphabetical; per microbe
    a latest-render row, a reference+labelled row, and an all-language descriptions
    table."""
    out = ["# Renders overview", "",
           "Auto-generated by `overview.py`. Organised into **sets** (sections), microbes "
           "in **alphabetical order**. For each microbe: row 1 is the latest render of every "
           "style; row 2 is the real micrograph followed by the labelled figures (English "
           "layer shown — Latin/German toggle in the SVG/HTML); then the descriptions used, "
           "in every language. Global burn: [`RENDER-STATUS.md`](../RENDER-STATUS.md).", ""]
    for set_name, metas in sorted(by_set.items()):
        set_dir = root / "set" / set_name
        out += [f"## Set: `{set_name}`", ""]
        for m in sorted(metas, key=lambda x: x["microbe"]):
            microbe = m["microbe"]
            base = f"set/{set_name}"
            out += [f"### {m.get('name', microbe)} (`{microbe}`)",
                    m.get("short_description", ""), ""]
            # available themes (a final exists on disk)
            themes = [th for th in THEME_ORDER
                      if (set_dir / "finals" / f"{microbe}__{th}.avif").exists()]
            # header = the theme finals
            hdr = [THEME_LABEL[th] for th in themes]
            row1 = [f"![{th}]({base}/finals/{microbe}__{th}.avif)" for th in themes]
            # row 2: real micrograph, then labelled figures, padded to len(themes)
            row2 = []
            ref = set_dir / "finals" / f"{microbe}__reference.avif"
            row2.append(cell("**Reference (real)**",
                             f"![reference]({base}/finals/{microbe}__reference.avif)"
                             if ref.exists() else ""))
            for th in LABELLED_THEMES:
                svg = set_dir / "theme" / th / f"{microbe}.{th}.svg"
                if svg.exists():
                    row2.append(cell(f"**{THEME_LABEL[th]} · labelled**",
                                     f"![{th} labelled]({base}/theme/{th}/{microbe}.{th}.svg)"))
            while len(row2) < len(hdr):
                row2.append("—")
            row2 = row2[:len(hdr)] if len(hdr) else row2
            if hdr:
                out.append("| " + " | ".join(hdr) + " |")
                out.append("| " + " | ".join("---" for _ in hdr) + " |")
                out.append("| " + " | ".join(row1) + " |")
                out.append("| " + " | ".join(row2) + " |")
                out.append("")
            # descriptions in all languages
            d = load_desc(set_dir, microbe)
            if d:
                out += ["| Audience | English | Deutsch |", "| --- | --- | --- |"]
                for aud, ek, dk in [("Kids", "kids_en", "kids_de"),
                                    ("Adults", "adults_en", "adults_de"),
                                    ("Scientific", "sci_en", "sci_de")]:
                    en = str(d.get(ek, "")).replace("\n", " ").replace("|", "\\|")
                    de = str(d.get(dk, "")).replace("\n", " ").replace("|", "\\|")
                    out.append(f"| **{aud}** | {en} | {de} |")
                out.append("")
            out += [f"[full log]({base}/{microbe}.render.md) · "
                    f"[set overview]({base}/OVERVIEW.md)", "", "---", ""]
    (root / "OVERVIEW.md").write_text("\n".join(out) + "\n")


def last_avif(theme_dir: Path, microbe: str) -> Path | None:
    cands = sorted(theme_dir.glob(f"{microbe}.attempts/gen-*.avif"),
                   key=lambda p: int(re.search(r"gen-(\d+)", p.name).group(1)))
    return cands[-1] if cands else None


def ref_avif(root: Path, microbe: str) -> Path | None:
    c = glob.glob(str(root / "set" / "reference-microscopy" / "theme" / "*" /
                      f"{microbe}.attempts" / "real-*.avif"))
    if not c:
        return None
    # prefer the highest real-NN (the cleaned/edited display version)
    return Path(sorted(c, key=lambda p: int(re.search(r"real-(\d+)", p).group(1)))[-1])


def fmt_cost(c): return f"${c:.3f}"
def fmt_time(s): return f"{s:.0f}s" if s < 60 else f"{s/60:.1f}m"


def set_status_rows(metas):
    COLS = ["name", "styles", "model", "render count", "pass", "svg status",
            "time taken", "tokens used", "costs"]
    head = "| " + " | ".join(COLS) + " |\n| " + " | ".join("---" for _ in COLS) + " |"
    rows = []
    tok = cost = 0
    for m in metas:
        for th in m.get("themes", []) + ([m["reference"]] if m.get("reference") else []):
            rows.append("| " + " | ".join(str(x) for x in [
                m.get("name", m["microbe"]), th.get("styles", th.get("theme", "")),
                th.get("model", "—"), th.get("render_count", 0),
                "✅" if th.get("pass") else "❌", th.get("svg_status", "—"),
                fmt_time(th.get("time_s", 0)), th.get("tokens", 0),
                fmt_cost(th.get("cost_usd", 0.0))]) + " |")
            tok += th.get("tokens", 0) or 0
            cost += th.get("cost_usd", 0.0) or 0.0
    return head + "\n" + "\n".join(rows), tok, cost


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--renders-root", default="renders")
    args = ap.parse_args()
    root = Path(args.renders_root)

    by_set: dict[str, list] = {}
    for mf in sorted(glob.glob(str(root / "set" / "*" / "*.render.meta.json"))):
        m = json.loads(Path(mf).read_text())
        by_set.setdefault(m["set"], []).append(m)

    for set_name, metas in sorted(by_set.items()):
        set_dir = root / "set" / set_name
        finals = set_dir / "finals"
        finals.mkdir(exist_ok=True)
        doc = [f"# {set_name} — overview", "",
               "Final image per microbe × style (last attempt), the labelled SVG, and "
               "the real-microscopy reference. Status table at the bottom.", ""]
        for m in sorted(metas, key=lambda x: x["microbe"]):
            microbe = m["microbe"]
            doc += [f"## {m.get('name', microbe)} (`{microbe}`)",
                    m.get("short_description", ""), ""]
            cells_h, cells = [], []
            for th in THEME_ORDER:
                src = last_avif(set_dir / "theme" / th, microbe)
                if not src:
                    continue
                dst = finals / f"{microbe}__{th}.avif"
                shutil.copyfile(src, dst)
                cells_h.append(th)
                cells.append(f"![{th}](finals/{dst.name})")
            # reference
            rsrc = ref_avif(root, microbe)
            if rsrc:
                rdst = finals / f"{microbe}__reference.avif"
                shutil.copyfile(rsrc, rdst)
                cells_h.append("reference")
                cells.append(f"![reference](finals/{rdst.name})")
            if cells:
                doc.append("| " + " | ".join(cells_h) + " |")
                doc.append("| " + " | ".join("---" for _ in cells_h) + " |")
                doc.append("| " + " | ".join(cells) + " |")
            # labelled svgs — every built style (textbook, 3d, watercolor, …)
            for th in THEME_ORDER:
                svg = set_dir / "theme" / th / f"{microbe}.{th}.svg"
                if not svg.exists():
                    continue
                doc += ["",
                        f"**{th} — labelled** (English default, La/De toggle): "
                        f"[SVG](theme/{th}/{microbe}.{th}.svg) · "
                        f"[HTML](theme/{th}/{microbe}.{th}.html)",
                        f"![{th} labelled](theme/{th}/{microbe}.{th}.svg)"]
            doc += ["", f"Full log: [`{microbe}.render.md`]({microbe}.render.md)", ""]

        table, tok, cost = set_status_rows(metas)
        doc += ["## Status", "", table, "",
                f"**Set total: {tok:,} tokens · {fmt_cost(cost)}**", "",
                f"_Updated {time.strftime('%Y-%m-%d %H:%M')} local._", ""]
        (set_dir / "OVERVIEW.md").write_text("\n".join(doc))

        # per-theme galleries (one markdown per style, linked from RENDER-STATUS)
        for th in THEME_ORDER:
            tdir = set_dir / "theme" / th
            if not tdir.exists():
                continue
            tdoc = [f"# {set_name} · {th} — gallery", "",
                    f"Every microbe's `{th}` image — labelled SVG where built, else "
                    f"the last render. [← set overview](../../OVERVIEW.md)", ""]
            for m in sorted(metas, key=lambda x: x["microbe"]):
                microbe = m["microbe"]
                svg = tdir / f"{microbe}.{th}.svg"
                if svg.exists():
                    img = f"![{th}]({svg.name})"
                else:
                    src = last_avif(tdir, microbe)
                    if not src:
                        continue
                    img = f"![{th}]({src.relative_to(tdir)})"
                tdoc += [f"## {m.get('name', microbe)} (`{microbe}`)",
                         img,
                         f"[full log](../../{microbe}.render.md)", ""]
            (tdir / "OVERVIEW.md").write_text("\n".join(tdoc))
        print(f"wrote {set_dir/'OVERVIEW.md'}  ({len(metas)} microbes, {fmt_cost(cost)})")

    build_root_index(by_set, root)
    print(f"wrote {root/'OVERVIEW.md'}")


if __name__ == "__main__":
    main()
