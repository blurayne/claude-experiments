"""Generate OVERVIEW.md — the single inventory of what this atlas contains.

Everything here is read from live sources, never hand-maintained, because the
two documents this replaces (MICROBES.md and GIANTMICROBES.md) both drifted out
of date within days of being written:

  cells_data.py            the catalogue: which microbes should exist
  viewer-data.json         what the built site actually serves
  renders/set/**           what has been rendered
  microbe_scale.py         size / weight per microbe
  microbe_giant.py         plush links, and which photos we had to repair
  ../giant-microbes/merged_catalog.json   what GIANTmicrobes sells

Run after build_viewer.py:

    uv run build_overview.py
"""
from __future__ import annotations

import json
import re
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
GM_CATALOG = HERE.parent / "giant-microbes" / "merged_catalog.json"
OUT = HERE / "OVERVIEW.md"

sys.path.insert(0, str(HERE))
import cells_data  # noqa: E402
from microbe_giant import GIANT, AI_CLEANED  # noqa: E402
from microbe_scale import SCALE, weight_class, weight_pg  # noqa: E402

IMG_STYLES = ["reference", "sem", "3d", "textbook", "watercolor"]
SVG_STYLES = ["textbook", "3d", "watercolor"]
YES, NO = "✅", "—"


def slugify(name: str) -> str:
    name = re.sub(r"\([^)]*\)", " ", name)
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def fmt_scale(key: str) -> str:
    if key not in SCALE:
        return NO
    um, val, unit = SCALE[key]
    size = f"{um:g} µm" if um >= 1 else f"{um * 1000:g} nm"
    return f"{size} · {val:g} {unit}"


def load_gm():
    """Group the GIANTmicrobes catalogue by species/base concept."""
    if not GM_CATALOG.is_file():
        return {}
    rows = json.loads(GM_CATALOG.read_text())
    groups = defaultdict(list)
    for x in rows:
        sp = (x.get("species") or "").strip().lower()
        name = x.get("name") or x.get("name_us") or ""
        base = re.split(
            r"\s+(Petri|Keychain|Gigantic|Mini|Ornament|Sticker|Mug|Scarf|Tie|Earrings|2-pack|Box)",
            re.sub(r"^(GIGANTISCHEmikrobe|Riesen)\s+", "", name),
        )[0].strip()
        key = sp or base.lower()
        if key:
            groups[key].append(x)
    return groups


def gm_rank(group):
    types = {x.get("product_type") for x in group}
    in_us = any(x.get("status_us") == "in_stock" for x in group)
    in_de = any(x.get("status_de") == "in_stock" for x in group)
    return (
        len(group) + 3 * in_us + 3 * in_de
        + 2 * ("Keychain" in types) + 2 * ("XL/Gigantic Plush" in types),
        in_us, in_de, types,
    )


def build():
    data = json.loads((HERE / "viewer-data.json").read_text())
    live = {m["key"]: (s, m) for s in data["sets"] for m in s["microbes"]}
    live_names = {m["name"]["en"] for _, m in live.values()}

    rendered_keys = set()
    for meta in (HERE / "renders" / "set").glob("*/*.render.meta.json"):
        if meta.parent.name in ("reference-microscopy", "set"):
            continue
        j = json.loads(meta.read_text())
        rendered_keys.add(j.get("microbe") or meta.name.split(".")[0])

    out = []
    A = out.append
    A("# Microbes atlas — complete inventory\n")
    A("*Generated by `build_overview.py` from `cells_data.py`, `viewer-data.json`, "
      "`renders/set/**`, `microbe_scale.py`, `microbe_giant.py` and the GIANTmicrobes "
      "catalogue. Do not edit by hand — rerun the script.*\n")

    # ---------- summary ----------
    total_cat = sum(len(p["entries"]) for p in cells_data.PAGES)
    A("## Where we stand\n")
    A(f"- **{len(data['sets'])} sets**, **{len(live)} microbes** live in the viewer, "
      f"out of **{total_cat} catalogued**.")
    A(f"- Every live microbe carries: {len(IMG_STYLES)} picture styles, "
      f"{len(SVG_STYLES)} labelled diagrams, a printable A4 coloring page, "
      f"kids narration in EN + DE, and size/weight data — the table below is the proof.")
    A(f"- **{len(GIANT)} plush links**, every one an exact species/cell match. "
      f"{len(AI_CLEANED)} of those photos had to be repaired (see the last section).\n")

    # ---------- the big table ----------
    A("## Every catalogued entry, and what it has\n")
    A("`R` = the 5 picture styles · `D` = the 3 labelled diagrams · "
      "`C` = coloring page · `A` = audio EN+DE · `S` = size/weight · `P` = plush link.\n")
    A("| Set | Microbe | key | R | D | C | A | S | P |")
    A("| --- | --- | --- | --- | --- | --- | --- | --- | --- |")

    missing_render = []
    for page in cells_data.PAGES:
        for e in page["entries"]:
            name = e["name_en"]
            key = next((k for k, (_s, m) in live.items() if m["name"]["en"] == name), None)
            if key is None and slugify(name) in live:
                key = slugify(name)
            if key is None:
                missing_render.append((page["id"], name))
                A(f"| {page['id']} | {name} | — | ❌ not rendered | | | | "
                  f"{fmt_scale(slugify(name))} | |")
                continue
            _set, m = live[key]
            nimg, nsvg = len(m.get("img") or {}), len(m.get("svg") or {})
            aud = m.get("audio") or {}
            A(
                f"| {page['id']} | {name} | `{key}` "
                f"| {nimg}/5 | {nsvg}/3 "
                f"| {YES if m.get('coloring') else NO} "
                f"| {YES if aud.get('en') and aud.get('de') else NO} "
                f"| {fmt_scale(key)} "
                f"| {GIANT[key][0] if key in GIANT else NO} |"
            )
    A("")

    # ---------- gaps ----------
    A("## Gaps\n")
    if missing_render:
        A(f"**Catalogued but not yet rendered — {len(missing_render)}.** Text, German "
          "translation and scale data already exist for these; only the pictures are missing.\n")
        for pid, name in missing_render:
            A(f"- `{pid}` — {name}")
    else:
        A("**Catalogued but not rendered:** none.")
    A("")

    orphan_render = sorted(rendered_keys - set(live))
    A(f"**Rendered but not reaching the viewer — {len(orphan_render)}.** "
      "A render only appears if `meta.name` matches a catalogue `name_en` exactly, "
      "or its key matches the slug of one; anything here fell through both.\n")
    for k in orphan_render:
        A(f"- `{k}`")
    if not orphan_render:
        A("- none")
    A("")

    orphan_scale = sorted(set(SCALE) - set(live))
    orphan_plush = sorted(set(GIANT) - set(live))
    A(f"**Data waiting for a render:** {len(orphan_scale)} scale entries "
      f"({', '.join('`'+k+'`' for k in orphan_scale) if orphan_scale else 'none'}), "
      f"{len(orphan_plush)} plush links "
      f"({', '.join('`'+k+'`' for k in orphan_plush) if orphan_plush else 'none'}).\n")

    no_ref = sorted(k for k, (_s, m) in live.items() if not (m.get("ref") or {}).get("url"))
    A(f"**No recorded micrograph source:** "
      f"{', '.join('`'+k+'`' for k in no_ref) if no_ref else 'none'}.\n")

    # ---------- GIANTmicrobes ----------
    groups = load_gm()
    if groups:
        A("## GIANTmicrobes — what they sell that we do not have\n")
        A("The catalogue has no sales figures, so prominence is inferred from what the "
          "vendor bets on: how many spin-offs a microbe gets (keychain, Gigantic, petri "
          "dish), whether it is still stocked, and whether both the US and German stores "
          "carry it. Only microbe-like products are listed — organs, dinosaurs and merch "
          "are skipped.\n")
        linked = {v[0] for v in GIANT.values()}
        rows = []
        for gkey, group in groups.items():
            plush = sorted(group, key=lambda x: 0 if x.get("product_type") == "Plush" else 1)[0]
            name = plush.get("name") or ""
            types = {x.get("product_type") for x in group}
            if not ({"Plush", "XL/Gigantic Plush"} & types):
                continue
            latin = (plush.get("species") or "").strip()
            paren = re.search(r"\(([^)]+)\)", name)
            latin = latin or (paren.group(1) if paren else "")
            if not latin:
                continue
            score, in_us, in_de, _ = gm_rank(group)
            rows.append((score, name, latin, len(group), in_us, in_de, name in linked))
        rows.sort(reverse=True)
        A("| Score | Product | Species | Variants | Stocked | Linked from our atlas |")
        A("| ---: | --- | --- | ---: | --- | --- |")
        for score, name, latin, n, iu, idd, have in rows[:30]:
            stock = " + ".join([s for s, f in (("US", iu), ("DE", idd)) if f]) or "retired"
            A(f"| {score} | {name[:44]} | *{latin[:30]}* | {n} | {stock} | "
              f"{YES if have else '**no**'} |")
        A("")

    # ---------- deliberate non-links ----------
    A("## Plush links we deliberately do not make\n")
    A("A plush is linked only when it depicts *this* cell or *this* species, checked "
      "against the catalogue's `species` field — not a relative, a precursor or the same "
      "family. The full reasoning lives in `microbe_giant.py`; in short: one generic "
      "\"Stem Cell\" plush is a haematopoietic stem cell and maps to that alone; \"Glial "
      "Cell\" depicts no particular glia; \"Bone Cell\" is an osteocyte; \"Obesity (Fat "
      "Cell)\" is the mature white adipocyte; \"White Blood Cell\" is a generic leukocyte; "
      "the \"Antibody\" plush is a plain Y-shaped monomer, so only IgG gets it; and their "
      "\"Hepatitis\" plush is hepatitis **C**, not B.\n")

    if AI_CLEANED:
        A("### Repaired photos\n")
        A("The vendor publishes some product shots only as soft, upscaled or "
          "logo-covered files. These were repaired with `scripts/edit_image.py` and are "
          "flagged in the viewer so none is passed off as an untouched product shot:\n")
        for k in sorted(AI_CLEANED):
            A(f"- `{k}` — {GIANT.get(k, ('(unlinked)',))[0]}")
        A("\nCandida and the trypanosome were deliberately **not** repaired: two attempts "
          "each, the second demanding a pixel-for-pixel result, and both times the model "
          "re-framed and cropped the toy. A soft but truthful photo beats a sharp but "
          "altered one.\n")

    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT.name}: {len(live)} live / {total_cat} catalogued, "
          f"{len(missing_render)} unrendered, {len(GIANT)} plush links")


if __name__ == "__main__":
    build()
