import { defineConfig } from 'vite'
import { viteSingleFile } from 'vite-plugin-singlefile'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))

/**
 * Galactic Transit builds back into exactly one file.
 *
 * The page is a PWA whose service worker caches `galactic-transit.html` by name and whose
 * build stamp is substituted into that file by `.github/scripts/build_site.py`. Neither
 * knows anything about modules, so the shape of the artifact must not change: `src/` in,
 * one self-contained `galactic-transit.html` out, sitting beside the data files it fetches
 * at runtime (`earth-map.webp`, `stars-gaia.bin`, `music/`, `sfx/`) exactly as before.
 *
 * Those runtime files are deliberately NOT inputs to this build. They are fetched by URL
 * from JS at runtime, they are large, and several are regenerated by a separate Python
 * workflow on GitHub's runners. Vite never sees them; the output simply lands in the
 * directory where they already live.
 */
export default defineConfig({
  root: resolve(HERE, 'src'),
  publicDir: false,
  base: './',

  build: {
    outDir: HERE,
    emptyOutDir: false, // the output directory is the project itself — never wipe it
    target: 'es2022',
    modulePreload: { polyfill: false },
    assetsInlineLimit: Number.MAX_SAFE_INTEGER,
    cssCodeSplit: false,
    rollupOptions: {
      input: resolve(HERE, 'src/galactic-transit.html'),
    },
    // The page is read as source by anyone who opens it; keep it legible. Terser-style
    // mangling would also make a parity failure impossible to diff by eye.
    minify: false,
  },

  // esbuild's TypeScript loader discards every comment, minified or not. On this page that
  // is not a cosmetic loss: the comments are where the reasoning lives — why the corotation
  // radius is what it is, why a trail is refilled rather than buffered, why the core glow is
  // gated from inside the disk — and a visitor who opens the page is meant to be able to
  // read them. Stripping ~1,000 lines of that is a change to the artifact, and this refactor
  // is not allowed to make changes to the artifact. So types are erased instead of
  // transpiled: ts-blank-space overwrites type syntax with spaces and touches nothing else,
  // which keeps every comment, every line number and every column exactly where it was.
  esbuild: false,

  plugins: [
    {
      name: 'ts-blank-space',
      enforce: 'pre',
      async transform(code, id) {
        if (!/\.ts$/.test(id.split('?')[0]!)) return null
        const { default: blank } = await import('ts-blank-space')
        // Identity source map: the output is the input with type syntax blanked in place.
        return { code: blank(code), map: null }
      },
    },

    viteSingleFile({ removeViteModuleLoader: true }),

    // GLSL needs no plugin of its own: Vite's `?raw` import hands the file's bytes to the
    // driver unaltered, which is the only acceptable behaviour here. A plugin that
    // reformatted a shader would be a rendering change wearing a build tool's clothes.
  ],

  define: {
    __DEV__: JSON.stringify(false),
  },
})
