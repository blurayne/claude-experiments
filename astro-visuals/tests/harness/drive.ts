import type { Page } from '@playwright/test'
import { readFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
export const SETTINGS_KEY = 'galactic-transit.settings.v1'

/**
 * Everything in this file exists to answer one question: what makes two runs of this page
 * draw the same pixels?
 *
 * Five things do not, and each is pinned below.
 *
 *  1. `Math.random`. The galaxy, both nebula fields, the dust, the belts and the starfield
 *     are all sampled. Seeded here, before any page script runs. Note the consequence for
 *     the refactor: the generators must consume randomness in the SAME ORDER as before, or
 *     the seed produces a different galaxy. That is deliberate — it is the property that
 *     turns "did you move this code correctly" into a pass/fail.
 *  2. The wall clock. The opening `simT` is the elapsed fraction of a year since 2026-01-01,
 *     and the HUD writes a calendar date. `Date` is frozen to a fixed instant.
 *  3. The first-launch performance probe. It measures the machine and picks a detail tier
 *     from the result (v2.73.0), which is exactly the kind of thing that differs between a
 *     laptop and a CI runner. It only runs when nothing is saved, so the harness always
 *     boots with a saved-settings fixture — which pins the tier and skips the probe.
 *  4. The first-visit tour, which covers the screen. Dismissed through its own button.
 *  5. Camera easing and the async map loaders. Both are settled by waiting for the frame to
 *     stop changing, rather than by sleeping for a guessed number of milliseconds.
 */

/** The settings blob every parity run boots with. Generated by `npm run baseline -- --refresh-fixture`. */
export function settingsFixture(): unknown {
  return JSON.parse(readFileSync(resolve(HERE, 'settings.fixture.json'), 'utf8'))
}

/** Frozen instant: 2026-06-15T12:00:00Z. Mid-year, midday, no DST edge, no leap second. */
export const FROZEN_NOW = Date.UTC(2026, 5, 15, 12, 0, 0)

export interface DeterminismOptions {
  seed?: number
  settings?: unknown
}

/**
 * Installed before the page's own script. Order matters: the error collector at the top of
 * the page is the first thing that runs, and it must see a world that is already pinned.
 */
export async function pinDeterminism(page: Page, opts: DeterminismOptions = {}): Promise<void> {
  const seed = opts.seed ?? 0x9e3779b9
  const settings = opts.settings ?? settingsFixture()

  await page.addInitScript(
    ({ seed, settings, key, now }: { seed: number; settings: unknown; key: string; now: number }) => {
      // mulberry32 — small, fast, and good enough that a galaxy sampled from it looks like
      // a galaxy. Determinism is the only requirement; statistical quality is not.
      let a = seed >>> 0
      Math.random = () => {
        a = (a + 0x6d2b79f5) >>> 0
        let t = a
        t = Math.imul(t ^ (t >>> 15), t | 1)
        t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
        return ((t ^ (t >>> 14)) >>> 0) / 4294967296
      }

      const RealDate = Date
      class FrozenDate extends RealDate {
        constructor(...args: unknown[]) {
          // `new Date()` is frozen; `new Date(x)` and `new Date(y, m, d)` are untouched,
          // because the page parses its own build stamp with the one-argument form.
          if (args.length === 0) super(now)
          else super(...(args as ConstructorParameters<typeof Date>))
        }
        static override now(): number {
          return now
        }
      }
      globalThis.Date = FrozenDate as unknown as DateConstructor

      try {
        localStorage.setItem(key, JSON.stringify(settings))
      } catch {
        /* storage disabled: the run will fall through to the probe and fail loudly */
      }
    },
    { seed, settings, key: SETTINGS_KEY, now: FROZEN_NOW },
  )
}

/** Load the page and get to a quiet, tour-free, paused frame. */
export async function boot(page: Page, url: string): Promise<void> {
  const errors: string[] = []
  page.on('pageerror', (e) => errors.push(String(e)))

  await page.goto(url + '?debug', { waitUntil: 'load' })
  await page.waitForFunction(() => !!document.getElementById('gl'))

  // The first visit is met by a full-screen overlay. AGENTS.md: dismiss it before any
  // screenshot, or the strip is four copies of the welcome card.
  const tour = page.locator('#tourGo')
  if (await tour.isVisible().catch(() => false)) await tour.click()

  await settle(page)

  if (errors.length) throw new Error(`page errors during boot:\n${errors.join('\n')}`)
}

/** Apply one of the page's own scenarios, through the selector and GO, as a visitor would. */
export async function applyScenario(page: Page, value: string): Promise<void> {
  await page.selectOption('#jump', value)
  await page.click('#jumpGo')
  await settle(page)
}

/** Read the page's own `exportState()` out through the debug dialog. */
export async function exportState(page: Page): Promise<Record<string, unknown>> {
  await page.evaluate(() => document.getElementById('dbgExport')!.dispatchEvent(new Event('click')))
  const json = await page.inputValue('#dbgText')
  return JSON.parse(json)
}

/**
 * Wait until the page stops changing.
 *
 * Not a sleep. Sleeping is what makes a headless suite flaky, and this page has three
 * independent reasons to still be moving after an action: the camera eases toward its goal
 * in log space, the galaxy and Andromeda maps load asynchronously and rebuild the point
 * buffers when they land, and the Gaia star file streams in. The honest test for "done" is
 * that consecutive frames are identical, so that is the test.
 *
 * SwiftShader runs this page at a few frames a second, which is why the interval is
 * generous and the budget is counted in attempts rather than milliseconds.
 */
export async function settle(page: Page, { tries = 40, interval = 250, needed = 3 } = {}): Promise<void> {
  let previous = ''
  let stable = 0

  for (let i = 0; i < tries; i++) {
    await page.waitForTimeout(interval)
    const shot = (await page.screenshot({ type: 'png' })).toString('base64')
    if (shot === previous) {
      if (++stable >= needed) return
    } else {
      stable = 0
      previous = shot
    }
  }
  throw new Error(`the frame never stopped changing after ${tries} attempts`)
}
